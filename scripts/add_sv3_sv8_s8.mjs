let added = 0
for (const { box_id, prefix, set } of SETS) {
  data.cards = data.cards.filter((c) => c.box_id !== box_id) // 再実行できるよう既存分は入れ替え
  for (const [no, rarity, name, type, stage, hp, illus, illusPop, charPop, apparel, specNote, colNote] of set.rows) {
    const id = `${prefix}-${no}`
    data.cards.push({
      id,
      card_no: `${String(no).padStart(3, '0')}/${set.total}`,
      rarity,
      card_name: name,
      box_id,
      is_reprint: false,
      image_url: set.img(no),
      card_spec: { type, stage, hp, note: specNote },
      materials: {
        player: { regulation_mark: set.reg, rotation: set.rotation, competitive_usage: 'none' },
        collector: { illustrator: illus, illustrator_popularity: illusPop, artwork_type: 'original', rarity },
        common: { reprint_status: 'none', scarcity: 'out_of_print', character_popularity: charPop },
      },
      evidence_notes: { player: '', collector: colNote, source: `${SRC} / https://snkrdunk.com/apparels/${apparel}` },
      note: '',
    })
    ids[id] = apparel
    added++
  }
}

